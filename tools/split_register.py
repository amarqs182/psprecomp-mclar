#!/usr/bin/env python3
"""Split the generated mc3_register.c into parallel-compilable chunks.

`mc3_register.c` is one translation unit with ~34,000 psp_register calls and
~98,000 forward declarations. Compiling it takes ~40 minutes and 2.1 GB RSS
on its own — it is by far the slowest part of the build and defeats
make -j entirely.

Split it into N chunks, each with its own forward-declaration block and its
own slice of the registration calls, plus a small dispatcher that calls the
chunks in order. The result compiles in seconds per chunk, in parallel.

Usage:
  split_register.py <mc3_register.c> <outdir> [chunks]
"""
import os
import re
import sys


def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__)
        return 2

    src_path, outdir = sys.argv[1], sys.argv[2]
    chunks = int(sys.argv[3]) if len(sys.argv) > 3 else 8

    with open(src_path, "r", encoding="utf-8") as fh:
        text = fh.read()

    lines = text.splitlines()

    # Locate the registration function body: the last "void psp_recomp_register(void) {"
    # line and the final "}" that closes it.
    fn_start = None
    for i, line in enumerate(lines):
        if re.match(r"^\s*void\s+psp_recomp_register\s*\(\s*void\s*\)\s*\{", line):
            fn_start = i
    if fn_start is None:
        print("ERROR: could not find psp_recomp_register()", file=sys.stderr)
        return 1

    # Body = the psp_register_* calls between fn_start and the closing brace.
    body = []
    for line in lines[fn_start + 1:]:
        stripped = line.strip()
        if stripped == "}":
            break
        body.append(stripped)
    calls = [c for c in body if c and not c.startswith("//")]
    if not calls:
        print("ERROR: no registration calls found", file=sys.stderr)
        return 1

    # Forward declarations: every "void psp_at_XXXX(void);" in the header block.
    decls = []
    for line in lines[:fn_start]:
        if re.match(r"^\s*void\s+psp_at_[0-9A-Fa-f]+\s*\(\s*void\s*\)\s*;", line):
            decls.append(line.strip())

    os.makedirs(outdir, exist_ok=True)

    # Split the calls evenly, preserving order.
    per = (len(calls) + chunks - 1) // chunks
    call_chunks = [calls[i * per:(i + 1) * per] for i in range(chunks)]
    call_chunks = [c for c in call_chunks if c]

    written = []
    for idx, chunk_calls in enumerate(call_chunks):
        fn = f"mc3_register_part{idx:02d}.c"
        path = os.path.join(outdir, fn)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("/* Generated by split_register.py -- do not edit.\n")
            fh.write(" *\n * One slice of the dispatch-table registration calls.\n")
            fh.write(" */\n")
            fh.write('#include "mc3_funcs.h"\n\n')
            for d in decls:
                fh.write(d + "\n")
            fh.write("\n")
            fh.write(f"void psp_recomp_register_part{idx:02d}(void) {{\n")
            for c in chunk_calls:
                fh.write("    " + c + "\n")
            fh.write("}\n")
        written.append((fn, len(chunk_calls)))

    # The dispatcher: calls each part in order.
    dispatcher = os.path.join(outdir, "mc3_register.c")
    with open(dispatcher, "w", encoding="utf-8") as fh:
        fh.write("/* Generated by split_register.py -- do not edit.\n")
        fh.write(" *\n * Dispatcher: runs the registration parts in order.\n")
        fh.write(" */\n")
        fh.write('#include "mc3_funcs.h"\n\n')
        for idx in range(len(call_chunks)):
            fh.write(f"void psp_recomp_register_part{idx:02d}(void);\n")
        fh.write("\n")
        fh.write("void psp_recomp_register(void) {\n")
        for idx in range(len(call_chunks)):
            fh.write(f"    psp_recomp_register_part{idx:02d}();\n")
        fh.write("}\n")

    total = sum(n for _, n in written)
    print(f"split {len(calls)} calls into {len(call_chunks)} parts "
          f"({total} calls, {len(decls)} decls each)")
    for fn, n in written:
        print(f"  {fn}: {n} calls")
    return 0


if __name__ == "__main__":
    sys.exit(main())
